/** Compact tuple → CountryCost helper so we can list every state and province. */
type Row = [
  key: string,
  name: string,
  petrol: number,
  diesel: number,
  charging: number,
  tollSystem: TollSystemType,
  tollNote: string,
  portalLabel: string,
  portalUrl: string,
  verified?: boolean,
];

function build(rows: Row[], flag: string, currency: string): CountryCost[] {
  return rows.map(([key, name, petrol, diesel, charging, tollSystem, tollNote, label, url, verified]) => ({
    key,
    name,
    flag,
    currency,
    petrol,
    diesel,
    charging,
    tollSystem,
    tollNote,
    portal: { label, url, verified: verified ?? false },
  }));
}

