function pointInPolygon(pt: LatLng, poly: LatLng[]): boolean {
  const [y, x] = pt;
  let inside = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [yi, xi] = poly[i]!;
    const [yj, xj] = poly[j]!;
    const intersect = yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi;
    if (intersect) inside = !inside;
  }
  return inside;
}

export function countryAt(pt: LatLng): string | null {
  for (const [code, poly] of Object.entries(COUNTRY_POLYGONS)) {
    if (pointInPolygon(pt, poly)) return code;
  }
  return null;
}
